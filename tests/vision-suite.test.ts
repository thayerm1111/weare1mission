import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const source=(path:string)=>readFileSync(path,"utf8");
const chart=source("src/components/om/vision/VisionChart.tsx");
const direction=source("src/components/om/vision/VisionDirection.tsx");
const strata=source("src/components/om/strata/StrataWorkspace.tsx");
const genx=source("src/components/om/genx/GenxHome.tsx");
const plays=source("src/components/om/plays/PlayDetail.tsx");
const atlas=source("src/components/om/atlas/AtlasSignalCard.tsx");
const atlasChart=source("src/components/om/atlas/AtlasSignalChart.tsx");
const command=source("src/components/command-center/hud/CommandCenterHud.tsx");

test("Trading tools retain chart-and-direction visuals and Atlas has a simplified gold briefing",()=>{
  assert.match(strata,/<VisionDirection/);
  assert.match(genx,/<VisionDirection/);
  assert.match(plays,/<VisionDirection/);
  assert.match(atlas,/<VisionDirection/);
  assert.match(command,/className="atlas-clear-brief"/);
  assert.match(atlasChart,/<VisionChart/);
  assert.match(plays,/<VisionChart/);
  assert.match(genx,/<VisionChart/);
  assert.match(source("src/components/om/strata/StrataChart.tsx"),/<VisionChart/);
});

test("Five visible candles come from actual source OHLC, not generated shapes or fake ticks",()=>{
  assert.match(chart,/\.slice\(-5\)/);
  assert.match(chart,/b\.h<Math\.max\(b\.o,b\.c,b\.l\)/);
  assert.match(chart,/b\.l>Math\.min\(b\.o,b\.c,b\.h\)/);
  assert.match(chart,/Map<number,TimedBar>/);
  assert.match(chart,/levels\.filter\(l=>isTrade\(l\.kind\)/);
  assert.match(chart,/priceLive/);
  assert.match(chart,/<OmChart bars=\{bars\}/);
  assert.doesNotMatch(chart,/Math\.random/);
});

test("Projection requires actual coherent entry, stop and target levels",()=>{
  assert.match(chart,/stop\.price<entry\.price/);
  assert.match(chart,/stop\.price>entry\.price/);
  assert.match(chart,/targets\.every\(t=>t\.price>entry\.price\)/);
  assert.match(chart,/targets\.every\(t=>t\.price<entry\.price\)/);
  assert.match(chart,/const scenario=directionValid&&entry&&targetLast/);
  assert.match(chart,/reference\?"Illustrated scenario only/);
});

test("STRATA always provides conditional research when defensible without arming FLOW",()=>{
  assert.match(strata,/generatePossibleEntry/);
  assert.match(strata,/liveIdea/);
  assert.match(strata,/MIXED STRUCTURE · SPECULATIVE SCENARIO ONLY/);
  assert.match(strata,/GENERATE BEST OPPORTUNITY/);
  assert.match(strata,/<VisionLevels/);
  assert.match(strata,/strata-vision-deep/);
  assert.doesNotMatch(strata,/placeMarketOrder/);
  assert.doesNotMatch(strata,/placeOnActiveAccounts/);
});

test("GENX is still generated by its original handler and tracking & confirmation remain available",()=>{
  assert.match(genx,/onClick=\{p\.analyze\}/);
  assert.match(genx,/<p\.Confirm setup=\{p\.setupOf\(g\)\}/);
  assert.match(genx,/onClick=\{p\.track\}/);
  assert.match(genx,/p\.backToCurrent/);
});
test("OM AI Plays keeps saved snapshots and manual confirmation, never silently executes",()=>{
  assert.match(plays,/atlasPlayChart\(r\)/);
  assert.match(plays,/snapshot/);
  assert.match(plays,/onDive/);
  assert.match(plays,/\{ticket\}/);
  assert.match(plays,/Opening the ticket only reviews accounts and risk/);
});
test("Atlas signals keep actual GENX/Plays result model and manual trade review",()=>{
  assert.match(atlas,/atlasExecution\(signal\)/);
  assert.match(atlas,/AtlasSignalChart/);
  assert.match(atlas,/onToggle=\{/);
  assert.match(atlas,/ExecuteSignal/);
  assert.match(command,/<GoldChart/);
  assert.match(command,/<ReadCard/);
  assert.match(command,/className="atlas-clear-brief"/);
});
test("Score is never presented as a promised win probability",()=>{
  assert.match(direction,/scoreName/);
  assert.match(strata,/STRUCTURE SCORE/);
  assert.match(command,/EVIDENCE STRENGTH/);
  assert.match(command,/not the probability of a winning trade/);
});

test("Atlas has direct navigation and a prominent signal button using its own existing generator",()=>{
  const nav=source("src/lib/floor/nav.ts");
  const shell=source("src/components/om/AppShell.tsx");
  const floor=source("src/components/om/floor/AtlasLiveDesk.tsx");
  assert.match(nav,/key: "atlas", label: "Gold Center", href: "\/command-center", hard: true/);
  assert.match(shell,/key: "atlas" as const, label: "Atlas Command Center".*href: "\/command-center", hard: true/);
  assert.doesNotMatch(shell,/if \(n\.key === "atlas"\) return <button/);
  assert.match(shell,/className="om-os-ask".*openAtlas\(\)/);
  assert.match(floor,/href="\/command-center" className="om-terminal-center-link"/);
  assert.match(command,/data-generate-primary="" onClick=\{generate\}/);
  assert.match(command,/Generate Gold Signal/);
  assert.match(command,/setIdeaMounted\(true\); setIdeaRun\(Date\.now\(\)\); setDrawer\("idea"\)/);
  assert.match(command,/endpoint=\{isReplay \? endpoint : "\/api\/command-center\/idea"\}/);
  assert.match(command,/What Atlas is watching/);
  assert.match(command,/What changes the view/);
  assert.match(command,/May return no valid trade\. Does not place an order/);
});

